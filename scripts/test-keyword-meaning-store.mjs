import assert from "node:assert/strict";
import {createHash} from "node:crypto";
import {DatabaseSync} from "node:sqlite";
import {buildKeywordMeaningStory} from "./keyword-meaning-story.mjs";
import {storeKeywordMeaning} from "./keyword-meaning-store.mjs";
const packets=[{task_id:"t",evidence_packet_digest:"d",serp:{pages:[]},demand_observations:[{evidence_id:"q"}]}];
const {evidence_packet_digest,...packetBody}=packets[0];
packets[0].evidence_packet_digest=createHash('sha256').update(JSON.stringify(packetBody)).digest('hex');
const node={id:"n",task_id:"t",evidence_packet_digest:"d",reader:"reader",trigger:"trigger",prior_knowledge:"known",problem:"problem",barrier:"barrier",desired_outcome:"outcome",answer_scope:"scope",rationale:"reason",evidence_ids:["q"],alternative_interpretations:[],unknowns:[]};
node.evidence_packet_digest=packets[0].evidence_packet_digest;
const story=buildKeywordMeaningStory(packets,[node],[]),db=new DatabaseSync(":memory:");
assert.equal(storeKeywordMeaning(db,{packets,story}).interpretations,1);
assert.equal(db.prepare("SELECT problem FROM meaning_interpretations").get().problem,"problem");
assert.equal(db.prepare("PRAGMA integrity_check").get().integrity_check,"ok");
assert.throws(()=>storeKeywordMeaning(db,{packets,story}),/already exists/);
assert.equal(db.prepare("SELECT COUNT(*) n FROM meaning_interpretations").get().n,1);
assert.throws(()=>storeKeywordMeaning(db,{packets,story:{...story,story_digest:"bad"}}),/digest/);
db.close();
const review={context:'応募理由',task_ids:['t'],auto_replacement:false,independently_verified:false,decisions:[{left:'語A',right:'語B',state:'exclude_other_sense',reason:'文脈が異なる',evidence_digest:'a'.repeat(64)}]};
const lexicalDb=new DatabaseSync(':memory:');
assert.throws(()=>storeKeywordMeaning(lexicalDb,{packets,story,lexicalReviews:[{...review,task_ids:['unknown']}]}),/scope/);
storeKeywordMeaning(lexicalDb,{packets,story,lexicalReviews:[review]});
assert.equal(lexicalDb.prepare('SELECT COUNT(*) n FROM meaning_lexical_review_tasks').get().n,1);
assert.equal(JSON.parse(lexicalDb.prepare('SELECT payload_json FROM meaning_lexical_reviews').get().payload_json).decisions[0].state,'exclude_other_sense');
lexicalDb.close();
console.log("keyword meaning store: OK (transactional projection, references, digest check, no overwrite)");

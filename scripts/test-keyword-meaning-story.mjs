import assert from "node:assert/strict";
import {createHash} from "node:crypto";
import {buildKeywordMeaningStory as build} from "./keyword-meaning-story.mjs";
const packet={task_id:"t",evidence_packet_digest:"a".repeat(64),demand_observations:[{evidence_id:"q"}],serp:{pages:[]}};
const {evidence_packet_digest,...packetBody}=packet;
packet.evidence_packet_digest=createHash('sha256').update(JSON.stringify(packetBody)).digest('hex');
const node=id=>({id,task_id:"t",evidence_packet_digest:packet.evidence_packet_digest,reader:"購入前の人",trigger:"選択肢が多い",prior_knowledge:"製品名",problem:"選ぶ基準がない",barrier:"違いを説明できない",desired_outcome:"条件に合う候補を選べる",answer_scope:"条件と比較軸",rationale:"質問が比較軸を求める",evidence_ids:["q"],alternative_interpretations:[],unknowns:["個人の予算"]});
const same=(from,to)=>({from,to,kind:"same_problem",shared_answer:"条件別の比較軸",rationale:"同じ読者と課題を同じ回答で解決する"});
const next=(from,to)=>({from,to,kind:"next_question",rationale:"候補を選べた後の準備",resolved_before_transition:"候補の絞り込み",next_question:"購入前に何を確認するか"});
const a=node("a"),b=node("b"),c=node("c"),before=JSON.stringify([a,b,c]);
assert.equal(build([packet],[a,b],[same("a","b")]).problem_clusters.length,1);
assert.equal(build([packet],[a,b,c],[same("a","b"),same("b","c")]).problem_clusters.length,2);
assert.throws(()=>build([packet],[a,{...b,reader:"購入後の人"}],[same("a","b")]),/incompatible/);
assert.throws(()=>build([packet],[{...a,evidence_ids:["invented"]}],[]),/unbound/);
assert.throws(()=>build([packet],[{...a,evidence_packet_digest:"stale"}],[]),/stale/);
assert.throws(()=>build([{...packet,demand_observations:[{evidence_id:'changed'}]}],[a],[]),/content digest/);
assert.throws(()=>build([packet],[a,b,c],[next("a","b"),next("b","c"),next("c","a")]),/cyclic/);
const result=build([packet],[a,b],[next("a","b")]);
assert.equal(result.story_transitions[0].actual_user_transition_observed,false);
assert.equal(result.dependency_order[0],result.story_transitions[0].from_problem);
assert.equal(JSON.stringify([a,b,c]),before);
assert.equal(result.independently_verified,false);
console.log("keyword meaning story: OK (evidence-bound interpretations, complete-link grouping, explicit transitions, cycles rejected)");
